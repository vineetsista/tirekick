#!/usr/bin/env node
/**
 * Copies the fixture report and its media into apps/web so the viewer can render
 * a real artifact.
 *
 * The report is copied into src/generated/ and imported statically rather than
 * read from disk at request time. That makes it part of the bundle - and because
 * the page parses it through the zod contract at module scope, a Python-side
 * schema change that the TypeScript side has not caught up with fails the web
 * build instead of failing in front of a buyer.
 *
 * Media goes to public/f/, which is gitignored - it is a copy, and fixtures/ is
 * the source of truth.
 */
import { cp, mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fixture = "demo-01";

const reportSrc = resolve(root, `fixtures/reports/${fixture}.report.json`);
const teaserSrc = resolve(root, `fixtures/reports/${fixture}.teaser.json`);
const mediaSrc = resolve(root, `fixtures/${fixture}/media`);
const generatedDir = resolve(root, "apps/web/src/generated");
const mediaDest = resolve(root, `apps/web/public/f/${fixture}`);

if (!existsSync(reportSrc)) {
  console.error(
    `missing ${reportSrc}\nrun: pnpm run inspect:fixture`,
  );
  process.exit(1);
}

await mkdir(generatedDir, { recursive: true });
await mkdir(mediaDest, { recursive: true });

await writeFile(
  resolve(generatedDir, `${fixture}.teaser.json`),
  await readFile(teaserSrc, "utf8"),
);

await writeFile(
  resolve(generatedDir, `${fixture}.report.json`),
  await readFile(reportSrc, "utf8"),
  "utf8",
);
await cp(mediaSrc, mediaDest, { recursive: true });

/**
 * The accuracy page is generated from docs/ACCURACY.md rather than retyped.
 * LAW 6 requires the product to link our own accuracy page including the misses;
 * a hand-maintained copy of that page would drift, and it would drift in the
 * flattering direction.
 */
const accuracy = await readFile(resolve(root, "docs/ACCURACY.md"), "utf8");
await writeFile(
  resolve(generatedDir, "accuracy.ts"),
  "// Generated by scripts/sync-fixture-to-web.mjs from docs/ACCURACY.md.\n" +
    "// Do not edit - edit the doc.\n" +
    `export const ACCURACY_MD = ${JSON.stringify(accuracy)};\n`,
  "utf8",
);

console.log(
  `synced ${fixture}: report + accuracy -> src/generated, media -> public/f/${fixture}`,
);
